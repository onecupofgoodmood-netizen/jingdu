function detectLocale() {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (locales.some((item) => item.code === saved)) return saved

  const browserLang = navigator.language?.toLowerCase() || ''
  if (browserLang.startsWith('fr')) return 'fr'
  if (browserLang.startsWith('es')) return 'es'
  if (browserLang.startsWith('en')) return 'en'
  return 'zh'
}

function getByPath(source, path) {
  return path.split('.').reduce((value, key) => value?.[key], source)
}

export function createI18n() {
  const locale = ref(detectLocale())

  const currentLocale = computed(() => locales.find((item) => item.code === locale.value) || locales[0])

  function setLocale(nextLocale) {
    if (!locales.some((item) => item.code === nextLocale)) return
    locale.value = nextLocale
  }

  function t(path, params = {}) {
    const value = getByPath(messages[locale.value], path) ?? getByPath(messages.zh, path) ?? path
    if (typeof value !== 'string') return value
    return value.replace(/\{(\w+)\}/g, (_, key) => params[key] ?? '')
  }

  watch(locale, (value) => {
    localStorage.setItem(STORAGE_KEY, value)
    document.documentElement.lang = value === 'zh' ? 'zh-CN' : value
    document.title = t('common.appTitle')
  }, { immediate: true })

  return { locale, locales, currentLocale, setLocale, t }
}

export function provideI18n(i18n) {
  provide(I18N_KEY, i18n)
}

export function useI18n() {
  const i18n = inject(I18N_KEY)
  if (!i18n) {
    throw new Error('i18n has not been provided')
  }
  return i18n
}
